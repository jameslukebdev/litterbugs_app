import 'server-only';

import { getCloudflareContext } from '@opennextjs/cloudflare';

type ImageInfo = { format: string; width?: number; height?: number; fileSize?: number };
type Transform = { width?: number; height?: number; fit?: 'scale-down' | 'cover'; gravity?: 'center' };
type Output = { format: 'image/jpeg' | 'image/webp'; quality: number; anim: false; background?: string };
type ImageBinding = {
  info: (stream: ReadableStream<Uint8Array>) => Promise<ImageInfo>;
  input: (stream: ReadableStream<Uint8Array>) => {
    transform: (options: Transform) => { output: (options: Output) => Promise<{ response: () => Response }> };
  };
};

export const usesCloudflareImages = () => process.env.LITTERBUGS_IMAGE_RUNTIME === 'cloudflare';

function binding() {
  const images = getCloudflareContext().env.IMAGES as ImageBinding | undefined;
  if (!images) throw new Error('Image processing is unavailable.');
  return images;
}

function stream(bytes: Uint8Array) {
  // No remote URL or signed source URL is sent to the image processor.
  return new Blob([new Uint8Array(bytes).buffer]).stream();
}

export async function inspectCloudflareImage(bytes: Uint8Array) {
  if (!bytes.byteLength || bytes.byteLength > 20 * 1024 * 1024) throw new Error('Image exceeds processing limit.');
  const info = await binding().info(stream(bytes));
  if (!Number.isSafeInteger(info.width) || !Number.isSafeInteger(info.height)
    || !info.width || !info.height || info.width < 1 || info.height < 1
    || info.format === 'image/svg+xml') throw new Error('Invalid raster image.');
  return { width: info.width, height: info.height, format: info.format };
}

/** Reject animation before passing arbitrary upload bytes to the decoder. */
export function isAnimatedRaster(bytes: Uint8Array) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const text = (offset: number, length: number) => String.fromCharCode(...bytes.subarray(offset, offset + length));
  if (bytes.length >= 12 && text(0, 4) === 'RIFF' && text(8, 4) === 'WEBP') {
    for (let offset = 12; offset + 8 <= bytes.length;) {
      const size = view.getUint32(offset + 4, true);
      if (text(offset, 4) === 'ANIM' || text(offset, 4) === 'ANMF'
        || (text(offset, 4) === 'VP8X' && size >= 1 && offset + 8 < bytes.length && (bytes[offset + 8] & 2) !== 0)) return true;
      offset += 8 + size + (size % 2);
    }
  }
  if (bytes.length >= 8 && text(1, 3) === 'PNG') {
    for (let offset = 8; offset + 12 <= bytes.length;) {
      const size = view.getUint32(offset);
      if (text(offset + 4, 4) === 'acTL') return true;
      offset += 12 + size;
    }
  }
  return false;
}

/** Strip APP/COM metadata from the trusted, freshly re-encoded JPEG header. */
export function stripJpegMetadata(bytes: Uint8Array) {
  if (bytes.length < 4 || bytes[0] !== 0xff || bytes[1] !== 0xd8) throw new Error('Invalid JPEG output.');
  const chunks = [bytes.subarray(0, 2)];
  let offset = 2;
  while (offset < bytes.length) {
    const start = offset;
    if (bytes[offset++] !== 0xff) throw new Error('Invalid JPEG segment.');
    while (bytes[offset] === 0xff) offset++;
    const marker = bytes[offset++];
    if (marker === 0xda) {
      // Scan payload is generated by Images, never copied from the source upload.
      if (offset + 2 > bytes.length || bytes[bytes.length - 2] !== 0xff || bytes[bytes.length - 1] !== 0xd9) throw new Error('Truncated JPEG output.');
      chunks.push(bytes.subarray(start));
      return Buffer.concat(chunks);
    }
    if (marker === 0xd9) throw new Error('JPEG output has no image scan.');
    if (offset + 2 > bytes.length) throw new Error('Truncated JPEG header.');
    const length = bytes[offset] * 256 + bytes[offset + 1];
    if (length < 2 || offset + length > bytes.length) throw new Error('Invalid JPEG segment size.');
    offset += length;
    if (!(marker >= 0xe0 && marker <= 0xef) && marker !== 0xfe) chunks.push(bytes.subarray(start, offset));
  }
  throw new Error('Truncated JPEG output.');
}

export async function renderCloudflareImage(bytes: Uint8Array, options: {
  width?: number; height?: number; cover?: boolean;
  format: 'image/jpeg' | 'image/webp'; quality: number; whiteBackground?: boolean;
}) {
  const info = await inspectCloudflareImage(bytes);
  let { width, height } = options;
  if (options.cover && width && height) {
    const scale = Math.min(1, info.width / width, info.height / height);
    width = Math.max(1, Math.floor(width * scale));
    height = Math.max(1, Math.floor(height * scale));
  }
  const image = await binding().input(stream(bytes))
    .transform({ ...(width ? { width } : {}), ...(height ? { height } : {}),
      fit: options.cover ? 'cover' : 'scale-down', ...(options.cover ? { gravity: 'center' } : {}) })
    .output({ format: options.format, quality: options.quality, anim: false,
      ...(options.whiteBackground ? { background: 'white' } : {}) });
  const response = image.response();
  if (!response.ok || response.headers.get('content-type')?.split(';')[0] !== options.format) throw new Error('Invalid image processor output.');
  const output = new Uint8Array(await response.arrayBuffer());
  if (!output.length || output.length > 20 * 1024 * 1024) throw new Error('Image output exceeds processing limit.');
  return options.format === 'image/jpeg' ? stripJpegMetadata(output) : Buffer.from(output);
}

/** Static files are served by the asset binding rather than a disk in Workers. */
export async function readCloudflareAsset(path: string) {
  if (!/^\/(brand|fonts)\/[A-Za-z0-9/_.-]+$/.test(path) || path.includes('..')) throw new Error('Invalid asset path.');
  const assets = getCloudflareContext().env.ASSETS;
  if (!assets) throw new Error('Static assets unavailable.');
  const response = await assets.fetch(new Request(`https://assets.invalid${path}`));
  if (!response.ok) throw new Error('Static asset unavailable.');
  return Buffer.from(await response.arrayBuffer());
}
